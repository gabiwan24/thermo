const glyphs = Object.fromEntries(Object.entries(drawings).map(([char, rows]) => [char, ['00000', '00000', ...rows.split('/')]]));
for (const [accent, base] of Object.entries({ Ä:'A', Ö:'O', Ü:'U', ä:'a', ö:'o', ü:'u' })) glyphs[accent] = ['01010', '00000', ...drawings[base].split('/')];
const aliases = { '–':'-', '—':'-', '„':'"', '“':'"', '”':'"', '’':"'", '\u00a0':' ' };

export const interfaceGlyphs = { ...glyphs };
for (const [char, base] of Object.entries(aliases)) interfaceGlyphs[char] = glyphs[base];

export function pixelText(text, width, { scale = 3, margin = 16, align = 'left' } = {}) {
  if (!Number.isInteger(width) || width < 8 || width % 8 || !Number.isInteger(scale) || scale < 1 || scale > 6 || !Number.isInteger(margin) || margin < 0 || width <= margin * 2) throw new Error('Ungültige Pixelgröße.');
  const normalized = [...text.normalize('NFC')].map(c => aliases[c] || c).join('').replace(/\t/g, ' ');
  const missing = [...new Set([...normalized].filter(c => c !== '\n' && c !== '\r' && !glyphs[c]))];
  if (missing.length) throw new Error(`In der Pixelschrift fehlen diese Zeichen: ${missing.join(' ')}. Bitte ersetzen oder Sans/Mono wählen.`);
  const measure = value => Math.max(0, [...value].length * 6 - 1) * scale;
  const lines = wrapText(normalized, width - margin * 2, measure);
  const lineHeight = 11 * scale;
  const height = margin * 2 + lines.length * lineHeight - 2 * scale;
  if (height > 1600) throw new Error('Der Text ist zu lang. Kürze ihn oder wähle eine kleinere Schrift.');
  const rgba = new Uint8ClampedArray(width * height * 4).fill(255);
  lines.forEach((line, lineIndex) => {
    const lineWidth = measure(line);
    const startX = align === 'center' ? Math.floor((width - lineWidth) / 2) : align === 'right' ? width - margin - lineWidth : margin;
    [...line].forEach((char, index) => glyphs[char].forEach((row, y) => [...row].forEach((dot, x) => {
      if (dot !== '1') return;
      for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
        const px = startX + index * 6 * scale + x * scale + dx;
        const py = margin + lineIndex * lineHeight + y * scale + dy;
        const p = (py * width + px) * 4;
        rgba[p] = rgba[p + 1] = rgba[p + 2] = 0;
      }
    })));
  });
  return { rgba, width, height };
}
